class RealTimeDetector:
    """
    Real-time ICU anomaly detection engine.

    Processes streaming vital sign readings and generates clinical alerts.

    Usage:
        detector = RealTimeDetector(model, config)
        detector.start_patient(patient_id="ICU_001")
        for reading in vital_sign_stream:
            alert = detector.process_reading(patient_id="ICU_001", reading=reading)
            if alert:
                notify_clinical_staff(alert)
    """

    def __init__(
        self,
        model: nn.Module,
        config: Optional[DetectorConfig] = None,
        device: str = "cpu",
    ) -> None:
        self.config = config or DetectorConfig()
        self.model = model.eval()
        self.device = torch.device(device)
        self.model = self.model.to(self.device)

        self.preprocessor = StreamPreprocessor(self.config)
        self.n_channels = len(self.config.channel_names)
        self.window_steps = self.config.window_hours * 12  # assuming 5-min resolution

        # Per-patient state
        self._buffers: Dict[str, RollingVitalBuffer] = {}
        self._state_machines: Dict[str, AlertStateMachine] = {}
        self._alert_histories: Dict[str, List[AlertEvent]] = {}
        self._score_histories: Dict[str, Deque[Tuple[datetime, float]]] = {}

        # Performance tracking
        self._inference_times: Deque[float] = deque(maxlen=100)

    def start_patient(self, patient_id: str) -> None:
        """Initialise monitoring state for a new patient."""
        self._buffers[patient_id] = RollingVitalBuffer(
            window_steps=self.window_steps,
            n_channels=self.n_channels,
        )
        self._state_machines[patient_id] = AlertStateMachine(self.config)
        self._alert_histories[patient_id] = []
        self._score_histories[patient_id] = deque(maxlen=1440)  # 24h at 1-min resolution
        logger.info(f"Started monitoring for patient: {patient_id}")

    def stop_patient(self, patient_id: str) -> None:
        """Clean up patient monitoring state."""
        for d in (self._buffers, self._state_machines,
                   self._alert_histories, self._score_histories):
            d.pop(patient_id, None)
        logger.info(f"Stopped monitoring for patient: {patient_id}")

    @torch.no_grad()
    def process_reading(
        self,
        patient_id: str,
        reading: VitalSignReading,
    ) -> Optional[AlertEvent]:
        """
        Process a single vital sign reading.

        Args:
            patient_id: Patient identifier
            reading:    New vital sign reading

        Returns:
            AlertEvent if an alert is triggered, else None
        """
        if patient_id not in self._buffers:
            self.start_patient(patient_id)

        # Preprocess
        normalised = self.preprocessor.reading_to_tensor(reading)
        self._buffers[patient_id].push(normalised, reading.timestamp)

        if not self._buffers[patient_id].is_ready():
            return None

        # Inference
        t0 = time.perf_counter()
        window = self._buffers[patient_id].get_window().to(self.device)  # (1, T, C)

        try:
            outputs = self.model(window)
        except Exception as e:
            logger.error(f"Inference error for patient {patient_id}: {e}")
            return None

        inference_ms = (time.perf_counter() - t0) * 1000
        self._inference_times.append(inference_ms)

        # Extract scores
        anomaly_score = float(outputs.get("anomaly_score", torch.tensor([0]))[0])
        channel_scores_tensor = outputs.get("channel_scores", torch.zeros(1, self.n_channels))[0]
        channel_scores = {
            ch: float(channel_scores_tensor[i])
            for i, ch in enumerate(self.config.channel_names)
        }

        # Risk probabilities
        risk_probs = {}
        if "outcome_logits" in outputs:
            probs = torch.sigmoid(outputs["outcome_logits"][0])
            outcome_names = getattr(self.model, "outcome_names", ["mortality", "sepsis", "vasopressor"])
            for i, name in enumerate(outcome_names):
                if i < probs.shape[0]:
                    risk_probs[name] = float(probs[i])

        # Record score history
        self._score_histories[patient_id].append((reading.timestamp, anomaly_score))

        # Update alert state machine
        alert_level, is_new_alert = self._state_machines[patient_id].update(
            anomaly_score, reading.timestamp
        )

        if not is_new_alert:
            return None

        # Build alert event
        contributing_channels = [
            ch for ch, sc in sorted(channel_scores.items(), key=lambda x: -x[1])[:3]
            if sc > 0.1
        ]

        alert = AlertEvent(
            patient_id=patient_id,
            timestamp=reading.timestamp,
            alert_level=alert_level,
            anomaly_score=anomaly_score,
            channel_scores=channel_scores,
            contributing_channels=contributing_channels,
            risk_probabilities=risk_probs,
            window_start=self._buffers[patient_id].window_start,
            window_end=reading.timestamp,
            alert_id=f"{patient_id}_{reading.timestamp.strftime('%Y%m%d%H%M%S')}",
            message=self._format_alert_message(alert_level, contributing_channels, risk_probs),
            recommended_action=self._recommend_action(alert_level, risk_probs),
        )

        self._alert_histories[patient_id].append(alert)
        logger.warning(
            f"ALERT [{alert_level}] Patient {patient_id} | "
            f"Score: {anomaly_score:.3f} | "
            f"Channels: {contributing_channels} | "
            f"Inference: {inference_ms:.1f}ms"
        )
        return alert

    def _format_alert_message(
        self,
        level: str,
        contributing_channels: List[str],
        risk_probs: Dict[str, float],
    ) -> str:
        """Generate human-readable alert message."""
        ch_str = ", ".join(c.replace("_", " ").title() for c in contributing_channels[:3])
        risk_str = ""
        for outcome, prob in sorted(risk_probs.items(), key=lambda x: -x[1]):
            if prob > 0.2:
                risk_str += f" P({outcome})={prob:.1%},"

        return (
            f"{level} deterioration alert. "
            f"Abnormal physiological pattern in: {ch_str}."
            f"{' Risk: ' + risk_str.rstrip(',') if risk_str else ''}"
        )

    def _recommend_action(
        self, level: str, risk_probs: Dict[str, float]
    ) -> str:
        """Generate recommended clinical action based on alert level."""
        actions = {
            "CRITICAL": "Immediate bedside assessment. Consider activating rapid response team.",
            "HIGH":     "Urgent bedside assessment within 15 minutes.",
            "MEDIUM":   "Clinical review within 30 minutes. Reassess vital signs.",
            "LOW":      "Increased monitoring frequency. Clinical review at next routine round.",
        }
        action = actions.get(level, "Clinical assessment recommended.")

        # Specific guidance based on risk type
        if risk_probs.get("sepsis", 0) > 0.5:
            action += " Sepsis bundle consideration: blood cultures, lactate, antibiotics."
        elif risk_probs.get("vasopressor", 0) > 0.5:
            action += " Haemodynamic instability: check fluid status, consider vasopressors."

        return action

    def process_batch(
        self,
        patient_id: str,
        readings: List[VitalSignReading],
    ) -> List[Optional[AlertEvent]]:
        """Process a batch of readings for a patient."""
        alerts = []
        for reading in readings:
            alert = self.process_reading(patient_id, reading)
            alerts.append(alert)
        return alerts

    def get_current_status(self, patient_id: str) -> Dict[str, Any]:
        """Get current monitoring status for a patient."""
        if patient_id not in self._buffers:
            return {"status": "not_monitoring"}

        score_history = list(self._score_histories.get(patient_id, []))
        recent_scores = [s for _, s in score_history[-12:]]  # last hour
        alert_history = self._alert_histories.get(patient_id, [])

        current_score = recent_scores[-1] if recent_scores else None
        level = "NONE"
        if current_score is not None:
            if current_score >= self.config.critical_threshold:
                level = "CRITICAL"
            elif current_score >= self.config.high_threshold:
                level = "HIGH"
            elif current_score >= self.config.medium_threshold:
                level = "MEDIUM"

        return {
            "patient_id": patient_id,
            "current_score": current_score,
            "current_level": level,
            "trend": float(np.diff(recent_scores[-3:]).mean()) if len(recent_scores) >= 3 else 0.0,
            "alerts_last_24h": len([
                a for a in alert_history
                if (datetime.utcnow() - a.timestamp).total_seconds() < 86400
            ]),
            "buffer_ready": self._buffers[patient_id].is_ready(),
            "avg_inference_ms": float(np.mean(self._inference_times)) if self._inference_times else None,
        }

    def get_dashboard_payload(self, patient_id: str) -> str:
        """Return JSON payload formatted for bedside dashboard display."""
        status = self.get_current_status(patient_id)
        score_history = list(self._score_histories.get(patient_id, []))
        recent_alerts = [
            a.to_dict() for a in self._alert_histories.get(patient_id, [])[-5:]
        ]

        payload = {
            "patient_id": patient_id,
            "updated_at": datetime.utcnow().isoformat(),
            **status,
            "score_timeline": [
                {"time": t.isoformat(), "score": float(s)}
                for t, s in score_history[-60:]  # last hour
            ],
            "recent_alerts": recent_alerts,
        }
        return json.dumps(payload, indent=2)


