# Rolling Buffer
# ---------------------------------------------------------------------------

class RollingVitalBuffer:
    """
    Maintains a rolling window of normalised vital sign arrays.

    Automatically forward-fills missing readings.
    """

    def __init__(
        self,
        window_steps: int,
        n_channels: int,
        max_gap_steps: int = 8,
    ) -> None:
        self.window_steps = window_steps
        self.n_channels = n_channels
        self.max_gap_steps = max_gap_steps
        self._buffer: Deque[np.ndarray] = deque(maxlen=window_steps)
        self._timestamps: Deque[datetime] = deque(maxlen=window_steps)
        self._last_valid: Optional[np.ndarray] = None
        self._gap_count: int = 0

    def push(self, values: np.ndarray, timestamp: datetime) -> None:
        """Add a new reading to the buffer, forward-filling if necessary."""
        # Forward-fill missing channels (nan → last valid value)
        if self._last_valid is not None:
            missing = np.isnan(values) | (values == 0)
            if missing.any():
                # Only fill if within max gap
                if self._gap_count <= self.max_gap_steps:
                    values = np.where(missing, self._last_valid, values)
                self._gap_count += 1
            else:
                self._gap_count = 0
                self._last_valid = values.copy()
        else:
            valid_mask = ~(np.isnan(values) | (values == 0))
            if valid_mask.any():
                self._last_valid = values.copy()

        self._buffer.append(values.copy())
        self._timestamps.append(timestamp)

    def get_window(self) -> Optional[Tensor]:
        """
        Return current window as tensor (1, T, C) if buffer is full.
        Returns None if insufficient data.
        """
        if len(self._buffer) < self.window_steps:
            return None
        arr = np.array(list(self._buffer), dtype=np.float32)  # (T, C)
        arr = np.nan_to_num(arr, nan=0.0)
        return torch.from_numpy(arr).unsqueeze(0)  # (1, T, C)

    def is_ready(self) -> bool:
        return len(self._buffer) >= self.window_steps

    @property
    def window_start(self) -> Optional[datetime]:
        return self._timestamps[0] if self._timestamps else None

    @property
    def window_end(self) -> Optional[datetime]:
        return self._timestamps[-1] if self._timestamps else None


# ---------------------------------------------------------------------------
# Alert State Machine
# ---------------------------------------------------------------------------

class AlertStateMachine:
    """
    Manages alert state including persistence and cooldown logic.

    State transitions:
      NONE → (score > medium_thresh) → PENDING_MEDIUM
      PENDING_MEDIUM → (persists) → MEDIUM alert
      NONE/MEDIUM → (score > high_thresh for N steps) → HIGH alert
      Any → (cooldown active) → suppressed
    """

    def __init__(self, config: DetectorConfig) -> None:
        self.config = config
        self._consecutive_high = 0
        self._consecutive_medium = 0
        self._last_alert_time: Optional[datetime] = None
        self._alerts_today: int = 0
        self._alert_day: Optional[int] = None

    def update(
        self,
        anomaly_score: float,
        timestamp: datetime,
    ) -> Tuple[str, bool]:
        """
        Update state machine with new anomaly score.

        Returns:
            (alert_level, is_new_alert)
        """
        # Reset daily counter
        if self._alert_day != timestamp.day:
            self._alerts_today = 0
            self._alert_day = timestamp.day

        # Determine level from score
        if anomaly_score >= self.config.critical_threshold:
            level = "CRITICAL"
            self._consecutive_high += 1
            self._consecutive_medium += 1
        elif anomaly_score >= self.config.high_threshold:
            level = "HIGH"
            self._consecutive_high += 1
            self._consecutive_medium += 1
        elif anomaly_score >= self.config.medium_threshold:
            level = "MEDIUM"
            self._consecutive_high = 0
            self._consecutive_medium += 1
        else:
            level = "NONE"
            self._consecutive_high = 0
            self._consecutive_medium = 0
            return "NONE", False

        # Check persistence requirements
        if level in ("HIGH", "CRITICAL"):
            if self._consecutive_high < self.config.high_persistence_steps:
                return "PENDING", False
        elif level == "MEDIUM":
            if self._consecutive_medium < self.config.medium_persistence_steps:
                return "PENDING", False

        # Check cooldown
        if self._last_alert_time is not None:
            elapsed_minutes = (timestamp - self._last_alert_time).total_seconds() / 60
            if elapsed_minutes < self.config.cooldown_minutes:
                return level, False  # suppressed by cooldown

        # Check daily cap
        if self._alerts_today >= self.config.max_alerts_per_day:
            return level, False

        # Issue alert
        self._last_alert_time = timestamp
        self._alerts_today += 1
        return level, True


