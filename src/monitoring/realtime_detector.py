"""
Real-Time ICU Anomaly Detection and Alerting System.

Implements a streaming vital sign processing pipeline for bedside deployment:
  - Rolling anomaly score computation from incoming vital sign streams
  - Alert triggering with configurable threshold and persistence
  - Alert suppression / cooldown logic to reduce alarm fatigue
  - Dashboard-ready JSON output format
  - Designed for integration with EHR systems (HL7 FHIR, HL7v2)

System requirements for production:
  - Latency: < 500ms per update (achievable on CPU for batch size 1)
  - Input: 1-minute resolution vital signs (1h sliding window minimum)
  - Output: JSON alert events to nurse station dashboard or EHR

Alert logic:
  1. Compute anomaly score from current 6h window
  2. If score >= high_threshold AND persists for >= 2 consecutive updates: HIGH alert
  3. If score >= medium_threshold AND persists >= 1 update: MEDIUM alert
  4. Suppress alerts within cooldown_minutes of last alert (anti-fatigue)
  5. Publish alert JSON to output queue
"""

