class MonitoringSimulator:
    """
    Simulate real-time monitoring on historical MIMIC data.

    Replays vital signs from a completed ICU stay at configurable speed
    and evaluates alert performance vs. ground truth event times.
    """

    def __init__(
        self,
        detector: RealTimeDetector,
        speed_multiplier: float = 60.0,
    ) -> None:
        self.detector = detector
        self.speed_multiplier = speed_multiplier

    def simulate(
        self,
        patient_id: str,
        vitals_df,  # pd.DataFrame
        event_times: Optional[Dict[str, float]] = None,
        real_time: bool = False,
    ) -> Dict[str, Any]:
        """
        Simulate monitoring for a historical ICU stay.

        Args:
            patient_id:    Identifier for simulation
            vitals_df:     Time-indexed vital sign DataFrame
            event_times:   Dict of clinical event times (hours from ICU admit)
            real_time:     If True, sleep to simulate real-time playback

        Returns:
            simulation_result: dict with alerts, scores, performance vs. events
        """
        self.detector.start_patient(patient_id)
        alerts = []
        score_timeline = []

        icu_intime = vitals_df.index[0]

        for timestamp, row in vitals_df.iterrows():
            reading = VitalSignReading(
                timestamp=timestamp,
                heart_rate=row.get("heart_rate"),
                sbp=row.get("sbp"),
                dbp=row.get("dbp"),
                map=row.get("map"),
                spo2=row.get("spo2"),
                resp_rate=row.get("resp_rate"),
                temperature=row.get("temperature"),
                gcs=row.get("gcs"),
            )

            alert = self.detector.process_reading(patient_id, reading)
            status = self.detector.get_current_status(patient_id)
            score_timeline.append({
                "time": timestamp,
                "score": status.get("current_score", 0),
                "hours_from_admit": (timestamp - icu_intime).total_seconds() / 3600,
            })

            if alert:
                alert_hours = (timestamp - icu_intime).total_seconds() / 3600
                alerts.append({
                    "time": timestamp,
                    "hours_from_admit": alert_hours,
                    "level": alert.alert_level,
                    "score": alert.anomaly_score,
                })

            if real_time:
                time.sleep(60 / self.speed_multiplier)

        # Evaluate vs. ground truth
        performance = self._evaluate_alerts(
            alerts, event_times or {}, icu_intime
        )

        return {
            "patient_id": patient_id,
            "n_alerts": len(alerts),
            "alerts": alerts,
            "score_timeline": score_timeline,
            "performance": performance,
        }

    @staticmethod
    def _evaluate_alerts(
        alerts: List[Dict],
        event_times: Dict[str, float],
        icu_intime,
    ) -> Dict[str, Any]:
        """Evaluate alert performance against known event times."""
        results = {}
        for event_name, event_h in event_times.items():
            first_alert_h = None
            for a in alerts:
                if a["hours_from_admit"] < event_h:
                    first_alert_h = a["hours_from_admit"]
                    break

            results[event_name] = {
                "event_hours": event_h,
                "first_alert_hours": first_alert_h,
                "lead_time": (event_h - first_alert_h) if first_alert_h is not None else None,
                "detected": first_alert_h is not None,
            }
        return results


