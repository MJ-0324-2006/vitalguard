@dataclass
class VitalSignReading:
    """Single time-stamped vital sign reading."""
    timestamp: datetime
    heart_rate: Optional[float] = None
    sbp: Optional[float] = None
    dbp: Optional[float] = None
    map: Optional[float] = None
    spo2: Optional[float] = None
    resp_rate: Optional[float] = None
    temperature: Optional[float] = None
    gcs: Optional[float] = None

    def to_array(self, channel_order: List[str]) -> np.ndarray:
        """Convert to numpy array in specified channel order."""
        values = []
        for ch in channel_order:
            val = getattr(self, ch, None)
            values.append(float(val) if val is not None else np.nan)
        return np.array(values, dtype=np.float32)


@dataclass
class AlertLevel:
    """Alert severity levels."""
    NONE: str = "NONE"
    LOW: str = "LOW"
    MEDIUM: str = "MEDIUM"
    HIGH: str = "HIGH"
    CRITICAL: str = "CRITICAL"


@dataclass
class AlertEvent:
    """Alert event generated by the monitoring system."""
    patient_id: str
    timestamp: datetime
    alert_level: str
    anomaly_score: float
    channel_scores: Dict[str, float]
    contributing_channels: List[str]
    risk_probabilities: Dict[str, float]
    window_start: datetime
    window_end: datetime
    suppressed: bool = False
    alert_id: str = ""
    message: str = ""
    recommended_action: str = ""

    def to_dict(self) -> dict:
        d = asdict(self)
        d["timestamp"] = self.timestamp.isoformat()
        d["window_start"] = self.window_start.isoformat()
        d["window_end"] = self.window_end.isoformat()
        return d

    def to_json(self) -> str:
        return json.dumps(self.to_dict(), indent=2)


@dataclass
class DetectorConfig:
    """Configuration for the real-time detector."""
    # Window
    window_hours: int = 6
    step_minutes: int = 5          # re-score every 5 minutes

    # Channels
    channel_names: List[str] = field(default_factory=lambda: [
        "heart_rate", "sbp", "dbp", "map",
        "spo2", "resp_rate", "temperature", "gcs"
    ])

    # Alert thresholds
    high_threshold: float = 0.75     # anomaly score → HIGH
    medium_threshold: float = 0.55   # anomaly score → MEDIUM
    critical_threshold: float = 0.90  # anomaly score → CRITICAL

    # Persistence (anti-chattering)
    high_persistence_steps: int = 2   # must exceed high threshold for N steps
    medium_persistence_steps: int = 1

    # Anti-fatigue cooldown
    cooldown_minutes: int = 30        # suppress alerts within N minutes of last
    max_alerts_per_day: int = 48      # hard cap on daily alerts

    # Normalisation (should match training preprocessing stats)
    channel_means: Optional[Dict[str, float]] = None
    channel_stds: Optional[Dict[str, float]] = None

    # Physiological bounds (for input validation)
    channel_bounds: Optional[Dict[str, Tuple[float, float]]] = None


# ---------------------------------------------------------------------------
# Input validation and normalisation
# ---------------------------------------------------------------------------

class StreamPreprocessor:
    """
    Preprocess incoming vital sign readings for model inference.

    Handles:
      - Out-of-range value rejection
      - Missing value forward-fill
      - Z-score normalisation
    """

    DEFAULT_BOUNDS = {
        "heart_rate":  (20.0,  300.0),
        "sbp":         (40.0,  300.0),
        "dbp":         (20.0,  200.0),
        "map":         (20.0,  200.0),
        "spo2":        (60.0,  100.0),
        "resp_rate":   (4.0,   60.0),
        "temperature": (25.0,  45.0),
        "gcs":         (3.0,   15.0),
    }

    DEFAULT_MEANS = {
        "heart_rate": 84.0, "sbp": 121.0, "dbp": 63.0, "map": 82.0,
        "spo2": 97.0, "resp_rate": 18.0, "temperature": 37.0, "gcs": 13.0,
    }
    DEFAULT_STDS = {
        "heart_rate": 17.0, "sbp": 22.0, "dbp": 14.0, "map": 15.0,
        "spo2": 3.0, "resp_rate": 5.0, "temperature": 0.5, "gcs": 3.0,
    }

    def __init__(self, config: DetectorConfig) -> None:
        self.config = config
        self.bounds = config.channel_bounds or self.DEFAULT_BOUNDS
        self.means = config.channel_means or self.DEFAULT_MEANS
        self.stds = config.channel_stds or self.DEFAULT_STDS

    def validate_reading(self, reading: VitalSignReading) -> Dict[str, Optional[float]]:
        """Filter out-of-range values."""
        result = {}
        for ch in self.config.channel_names:
            val = getattr(reading, ch, None)
            if val is None or np.isnan(val):
                result[ch] = None
                continue
            lo, hi = self.bounds.get(ch, (-np.inf, np.inf))
            result[ch] = float(val) if lo <= val <= hi else None
        return result

    def normalize(self, values: Dict[str, Optional[float]]) -> np.ndarray:
        """Z-score normalise and fill missing with 0 (mean-normalised)."""
        arr = np.zeros(len(self.config.channel_names), dtype=np.float32)
        for i, ch in enumerate(self.config.channel_names):
            val = values.get(ch)
            if val is not None:
                mean = self.means.get(ch, 0)
                std = self.stds.get(ch, 1)
                arr[i] = (val - mean) / max(std, 1e-6)
            # else: leave as 0 (mean-substituted)
        return arr

    def reading_to_tensor(self, reading: VitalSignReading) -> np.ndarray:
        """Full pipeline: validate → normalise → return (C,) array."""
        validated = self.validate_reading(reading)
        return self.normalize(validated)


